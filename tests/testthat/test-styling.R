withr::local_dir(testthat::test_path("..", ".."))

testthat::test_that("map styling, zoom and generated code reproduce the loaded map", {
  app_env <- new.env(parent = globalenv())
  suppressWarnings(sys.source("app.R", envir = app_env))
  testthat::expect_match(as.character(app_env$ui), "toggle_canvas_size")
  testthat::expect_match(as.character(app_env$ui), "main_sidebar")
  extent <- sf::st_as_sfc(sf::st_bbox(c(xmin = 560000, ymin = 180000,
    xmax = 562000, ymax = 182000), crs = sf::st_crs(27700)))
  areas <- sf::st_sf(code = c("001", "002", "003", "004"), name = LETTERS[1:4],
    geometry = sf::st_make_grid(extent, n = c(2, 2)))
  areas$value <- c(0, 10, 20, NA)
  path <- tempfile(fileext = ".gpkg")
  on.exit(unlink(path))
  sf::st_write(areas, path, layer = "areas", quiet = TRUE)
  csv_path <- tempfile(fileext = ".csv")
  readr::write_csv(data.frame(code = areas$code, numerator = 1:4, denominator = 10), csv_path)
  on.exit(unlink(csv_path), add = TRUE)
  plot_file <- tempfile(fileext = ".pdf")
  grDevices::pdf(plot_file)
  on.exit({ grDevices::dev.off(); unlink(plot_file) }, add = TRUE)
  shiny::testServer(app_env$server, {
    session$setInputs(folder = dirname(path), council_profile = "thurrock",
      base_file = path, base_layer = "areas", filter_column = "", format = "png",
      width = 4, height = 4, dpi = 100, ramp_low = "#000000", ramp_high = "#FFFFFF")
    session$setInputs(load_base = 1)
    testthat::expect_equal(nrow(state$map_data), 4)
    session$setInputs(csv = list(datapath = csv_path), boundary_key = "code", data_key = "code")
    session$setInputs(join = 1)
    session$setInputs(numerator = "data_numerator", denominator = "data_denominator")
    session$setInputs(percentage = 1)
    testthat::expect_equal(state$map_data$.map_percentage, c(10, 20, 30, 40))
    session$setInputs(overlay_file = path, overlay_layer = "areas", overlay_mode = "Full layer",
      overlay_name = "Areas", overlay_colour = "#333333", overlay_alpha = 0.7,
      overlay_size = 0.5, overlay_shape = "16", outline_only = TRUE, overlay_label = "")
    session$setInputs(add_overlay = 1)
    session$setInputs(selected_overlay = "1", edit_overlay_colour = "#AA0000",
      edit_overlay_variable = "value", edit_overlay_low = "#FFFFCC", edit_overlay_high = "#800026")
    session$setInputs(update_overlay_colour = 1)
    testthat::expect_equal(state$overlays[[1]]$variable, "value")
    session$setInputs(edit_overlay_linewidth = .1, update_overlay_width = 1)
    testthat::expect_equal(state$overlays[[1]]$linewidth, .1)
    style <- overlay_value_colours(state$overlays[[1]])
    testthat::expect_equal(tail(style$fill, 1), "#D9D9D9")
    testthat::expect_true(length(unique(style$fill)) > 2)
    session$setInputs(zoom_in = 1, label_colour = "#123456", label_font = "serif",
      legend_colour = "#654321", legend_font = "mono", labels = TRUE, label = "name",
      title_align = "right", canvas_boundary = TRUE,
      base_linewidth = .6, base_boundary_colour = "#112233")
    testthat::expect_equal(settings()$zoom, 1.25)
    session$setInputs(pan_left = 1)
    testthat::expect_gt(settings()$centre_x, 0.5)
    session$setInputs(pan_right = 1)
    testthat::expect_equal(settings()$centre_x, 0.5)
    session$setInputs(pan_up = 1)
    testthat::expect_lt(settings()$centre_y, 0.5)
    session$setInputs(pan_down = 1)
    testthat::expect_equal(settings()$centre_y, 0.5)
    plot <- current_plot()
    testthat::expect_equal(plot$layers[[1]]$aes_params$linewidth, .6)
    testthat::expect_equal(plot$layers[[1]]$aes_params$colour, "#112233")
    testthat::expect_equal(plot$theme$legend.text$family, "mono")
    testthat::expect_equal(plot$theme$plot.title$hjust, 1)
    testthat::expect_s3_class(plot$theme$panel.border, "element_rect")
    output_file <- tempfile(fileext = ".png")
    export_map(plot, output_file, 4, 4, 100)
    testthat::expect_gt(file.info(output_file)$size, 100)
    unlink(output_file)
    # The code uses loaded state even if the candidate file controls later change.
    session$setInputs(filter_column = "code", filter_values = "001")
    code <- reproduction_code()
    code <- sub("export_map\\(plot,.*$", "", code)
    reproduced <- new.env(parent = globalenv())
    eval(parse(text = code), envir = reproduced)
    testthat::expect_equal(reproduced$map_data, state$map_data)
    testthat::expect_equal(reproduced$settings, settings())
    testthat::expect_equal(reproduced$overlays[[1]]$data, state$overlays[[1]]$data)
    testthat::expect_equal(reproduced$overlays[[1]]$linewidth, .1)
    session$setInputs(apply_layer_ramp = 1)
    testthat::expect_equal(state$overlays[[1]]$variable, "")
    session$setInputs(reset_view = 1)
    testthat::expect_equal(settings()$zoom, 1)
    session$setInputs(overlay_name = "Second layer", add_overlay = 2)
    session$setInputs(selected_overlay = "2", lower_overlay = 1)
    testthat::expect_equal(state$overlays[[1]]$name, "Second layer")
    session$setInputs(selected_overlay = "1", raise_overlay = 1)
    testthat::expect_equal(state$overlays[[2]]$name, "Second layer")
    session$setInputs(selected_overlay = "2", toggle_overlay = 1)
    testthat::expect_false(state$overlays[[2]]$visible)
    session$setInputs(remove_overlay = 1)
    testthat::expect_length(state$overlays, 1)
    session$setInputs(selected_overlay = "1", remove_overlay = 2)
    testthat::expect_length(state$overlays, 0)
  })
})
